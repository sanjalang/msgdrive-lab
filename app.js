// Method C: write the content into the origin private file system first (piece by piece, as a decrypting page would), then
// hand the finished file to the system: the share sheet, or a download link to a blob URL of that file. The file is on
// disk, so neither step needs the content in memory.
let stagedUrl = null;
let stagedFile = null;

function clearStaged() {
  if (stagedUrl !== null) URL.revokeObjectURL(stagedUrl);
  stagedUrl = null;
  stagedFile = null;
  $('stageShare').disabled = true;
  $('stageLink').removeAttribute('href');
  $('stageLink').setAttribute('aria-disabled', 'true');
}

action('stageWrite', 'stageStatus', async () => {
  if (!features.opfs) {
    status('stageStatus', '這個瀏覽器沒有內部儲存空間的 API');
    return;
  }
  clearStaged();
  const size = Number($('dlSize').value);
  const name = `l0-dl-${size}.bin`;
  // 'worker': a synchronous access handle in a worker (charged what it writes on an iPhone); 'writable': a writable stream
  // on the page (every write is charged the whole file so far there)
  const method = $('stageMethod').value;
  const estimate = await navigator.storage.estimate();
  log(`e.stage start size=${size} method=${method} quota=${mib(estimate.quota ?? 0)} usage=${mib(estimate.usage ?? 0)}`);
  const directory = await navigator.storage.getDirectory();
  const handle = await directory.getFileHandle(name, { create: true });
  const started = performance.now();
  let writeMs = 0;
  let closeMs = 0;
  if (method === 'worker') {
    try {
      const result = await writeInWorker(name, size, PIECE, (progress) => {
        status('stageStatus', `寫入 ${mib(progress.position)} / ${mib(size)}`);
        log(`e.stage at=${mib(progress.position)} elapsed=${seconds(performance.now() - started)} write=${seconds(progress.writeMs)}`);
      });
      writeMs = result.writeMs;
      closeMs = result.closeMs;
    } catch (error) {
      await directory.removeEntry(name).catch(() => undefined);
      throw error;
    }
  } else {
    if (typeof handle.createWritable !== 'function') throw new Error('createWritable is not available on this browser');
    const writable = await handle.createWritable();
    let nextLog = 256 * MIB;
    try {
      for (let position = 0; position < size; ) {
        const end = Math.min(size, position + PIECE);
        const bytes = gen.range(position, end);
        const before = performance.now();
        await writable.write(bytes);
        writeMs += performance.now() - before;
        position = end;
        status('stageStatus', `寫入 ${mib(position)} / ${mib(size)}`);
        if (position >= nextLog) {
          nextLog += 256 * MIB;
          log(`e.stage at=${mib(position)} elapsed=${seconds(performance.now() - started)} write=${seconds(writeMs)}${heap()}`);
        }
      }
    } catch (error) {
      await writable.abort().catch(() => undefined);
      await directory.removeEntry(name).catch(() => undefined);
      throw error;
    }
    const beforeClose = performance.now();
    await writable.close();
    closeMs = performance.now() - beforeClose;
  }
  // Each step after the last write is timed on its own: on an iPhone 16 s passed here for 1 GiB, and the log did not say where
  const beforeGetFile = performance.now();
  const onDisk = await handle.getFile();
  const getFileMs = performance.now() - beforeGetFile;
  const beforeWrap = performance.now();
  // Wrapping does not copy: the new File refers to the one on disk
  stagedFile = new File([onDisk], name, { type: 'application/octet-stream' });
  stagedUrl = URL.createObjectURL(stagedFile);
  $('stageLink').href = stagedUrl;
  $('stageLink').download = name;
  $('stageLink').removeAttribute('aria-disabled');
  const wrapMs = performance.now() - beforeWrap;
  const beforeCanShare = performance.now();
  const canShare = typeof navigator.canShare === 'function' && navigator.canShare({ files: [stagedFile] });
  const canShareMs = performance.now() - beforeCanShare;
  $('stageShare').disabled = !canShare;
  log(`e.stage written size=${onDisk.size} sizeOk=${onDisk.size === size} write=${seconds(writeMs)} (${rate(size, writeMs)}) close=${seconds(closeMs)} getFile=${seconds(getFileMs)} wrap=${seconds(wrapMs)} canShare=${seconds(canShareMs)} canShareFiles=${canShare}`);
  status('stageStatus', `已寫入 ${mib(size)}(${seconds(writeMs)})。接著按「分享 / 儲存到檔案」或「用下載連結儲存」`);
});

