// ───────────────────────── e. Streamed download through the Service Worker ─────────────────────────

function newToken() {
  return Array.from(crypto.getRandomValues(new Uint8Array(8)), (byte) => byte.toString(16).padStart(2, '0')).join('');
}

function refreshDownloadLink() {
  $('dlLink').href = `dl/${newToken()}?size=${$('dlSize').value}&mode=${$('dlMode').value}&pace=${$('dlPace').value}`;
}

const downloads = new Map();
let piecesServed = 0;

function onWorkerMessage(event) {
  const data = event.data;
  if (!data) return;
  if (data.type === 'need') {
    // The Service Worker asks for one piece of the content (mode=page)
    const bytes = gen.range(data.start, data.end);
    piecesServed++;
    event.ports[0].postMessage({ bytes: bytes.buffer }, [bytes.buffer]);
    return;
  }
  if (data.type !== 'dl') return;
  const seen = downloads.get(data.token) ?? { nextLog: 64 * MIB };
  downloads.set(data.token, seen);
  const where = `${mib(data.position)} / ${mib(data.size)}`;
  if (data.state === 'start') {
    log(
      `e.start token=${data.token} mode=${data.mode} size=${data.size} hasClientId=${data.clientId !== ''} hasResultingClientId=${data.resultingClientId !== ''} pace=${data.pace} ` +
        `destination=${data.destination} requestMode=${data.requestMode}`,
    );
    status('dlStatus', `開始:${mib(data.size)}`);
  } else if (data.state === 'progress') {
    status('dlStatus', `瀏覽器已讀取 ${where},${rate(data.position, data.elapsedMs)}`);
    if (data.position >= seen.nextLog) {
      seen.nextLog = data.position + 64 * MIB;
      log(`e.progress token=${data.token} pulled=${where} elapsed=${seconds(data.elapsedMs)} (${rate(data.position, data.elapsedMs)})${heap()}`);
    }
  } else {
    log(`e.${data.state} token=${data.token} pulled=${where} elapsed=${seconds(data.elapsedMs)}${data.message ? ` message=${data.message}` : ''} piecesServedByPage=${piecesServed}${heap()}`);
    const words = { done: '瀏覽器讀完了', cancel: '被取消', error: '發生錯誤' };
    status('dlStatus', `${words[data.state] ?? data.state}:${where},${seconds(data.elapsedMs)}`);
  }
}

async function setUpServiceWorker() {
  if (!features.serviceWorker) {
    status('dlStatus', '這個瀏覽器沒有 Service Worker');
    return;
  }
  navigator.serviceWorker.onmessage = onWorkerMessage;
  try {
    await navigator.serviceWorker.register('sw.js');
    await navigator.serviceWorker.ready;
    if (!navigator.serviceWorker.controller) {
      await new Promise((resolve) => {
        navigator.serviceWorker.addEventListener('controllerchange', resolve, { once: true });
        setTimeout(resolve, 3000);
      });
    }
    const controlled = !!navigator.serviceWorker.controller;
    log(`e.serviceWorker controlled=${controlled}`);
    status('dlStatus', controlled ? 'Service Worker 已接管' : 'Service Worker 尚未接管,請重新整理一次');
  } catch (error) {
    log(`e.serviceWorker ERROR ${describeError(error)}`);
    status('dlStatus', `Service Worker 註冊失敗:${describeError(error)}`);
  }
}

