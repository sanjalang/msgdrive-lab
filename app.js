'use strict';

const MIB = 1048576;
const PIECE = 4 * MIB;
const sha = self.L0Sha256;
const gen = self.L0Gen;
const $ = (id) => document.getElementById(id);

// ───────────────────────── Log ─────────────────────────

const lines = [];
const pageStart = performance.now();

function log(text) {
  const line = `[${((performance.now() - pageStart) / 1000).toFixed(1).padStart(7)}s] ${text}`;
  lines.push(line);
  const box = $('log');
  box.append(document.createTextNode(`${line}\n`));
  box.scrollTop = box.scrollHeight;
}

function status(id, text) {
  $(id).textContent = text;
}

const mib = (bytes) => `${(bytes / MIB).toFixed(bytes < 10 * MIB ? 2 : 0)} MiB`;
const seconds = (ms) => `${(ms / 1000).toFixed(2)} s`;
const rate = (bytes, ms) => (ms > 0 ? `${(bytes / MIB / (ms / 1000)).toFixed(0)} MiB/s` : 'n/a');

/** JS heap in use (Chromium only; empty elsewhere) */
function heap() {
  const memory = performance.memory;
  return memory ? ` heap=${(memory.usedJSHeapSize / MIB).toFixed(0)}MiB` : '';
}

function describeError(error) {
  return error instanceof Error ? `${error.name}: ${error.message}` : String(error);
}

/** Runs one button action at a time; a failure goes to the log instead of the console only */
let busy = false;
function action(buttonId, statusId, run) {
  $(buttonId).addEventListener('click', async () => {
    if (busy) {
      status(statusId, '另一項測試還在進行');
      return;
    }
    busy = true;
    try {
      await run();
    } catch (error) {
      log(`ERROR ${buttonId}: ${describeError(error)}`);
      status(statusId, `失敗:${describeError(error)}`);
    } finally {
      busy = false;
    }
  });
}

