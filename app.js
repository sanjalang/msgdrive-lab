/** Everything at the top of the origin private file system. Only this page's own files (`l0-…`) are ever named or removed. */
async function listStaged(directory) {
  const entries = [];
  for await (const [name, handle] of directory.entries()) {
    let size = null;
    if (handle.kind === 'file') {
      try {
        size = (await handle.getFile()).size;
      } catch {
        size = null;
      }
    }
    entries.push({ name, kind: handle.kind, size, own: name.startsWith('l0-') });
  }
  return entries;
}

async function logStorage(directory, label) {
  const entries = await listStaged(directory);
  let total = 0;
  for (const entry of entries) {
    total += entry.size ?? 0;
    log(`e.stage entry kind=${entry.kind} size=${entry.size === null ? '?' : mib(entry.size)} name=${entry.own ? entry.name : '(not from this page)'}`);
  }
  const estimate = await navigator.storage.estimate();
  log(`e.stage ${label} entries=${entries.length} total=${mib(total)} usage=${mib(estimate.usage ?? 0)} quota=${mib(estimate.quota ?? 0)}`);
  return { count: entries.length, total, usage: estimate.usage ?? 0 };
}

action('stageList', 'stageStatus', async () => {
  const directory = await navigator.storage.getDirectory();
  const found = await logStorage(directory, 'list');
  status('stageStatus', `內部儲存空間裡有 ${found.count} 個項目,共 ${mib(found.total)};瀏覽器回報這個網站已用 ${mib(found.usage)}`);
});

action('stageRemove', 'stageStatus', async () => {
  clearStaged();
  const directory = await navigator.storage.getDirectory();
  let removed = 0;
  for (const entry of await listStaged(directory)) {
    if (!entry.own) continue;
    try {
      await directory.removeEntry(entry.name, { recursive: true });
      removed++;
    } catch (error) {
      log(`e.stage remove failed: ${describeError(error)}`);
    }
  }
  log(`e.stage removed files=${removed}`);
  const left = await logStorage(directory, 'after-remove');
  status('stageStatus', `已刪除 ${removed} 個暫存檔;剩下 ${left.count} 個項目,瀏覽器回報這個網站已用 ${mib(left.usage)}`);
});

// Ways of writing the staged file. On an iPhone the usage that the browser reports grew by 8320 MiB after one 256 MiB file
// written in 4 MiB pieces: exactly 4 + 8 + … + 256, as if every write were charged the whole file so far. This writes the
// same 256 MiB in several ways and logs the reported usage around each, to find a way that is charged what it writes.
const METHOD_SIZE = 256 * MIB;

async function storageNow() {
  const estimate = await navigator.storage.estimate();
  return { usage: estimate.usage ?? 0, quota: estimate.quota ?? 0 };
}

async function writeThroughWritable(handle, size, piece, truncateFirst) {
  const writable = await handle.createWritable();
  try {
    // With the size set first, no later write makes the file longer
    if (truncateFirst) await writable.truncate(size);
    for (let position = 0; position < size; ) {
      const end = Math.min(size, position + piece);
      await writable.write(gen.range(position, end));
      position = end;
    }
  } catch (error) {
    await writable.abort().catch(() => undefined);
    throw error;
  }
  await writable.close();
}

function writeInWorker(name, size, piece, onProgress) {
  return new Promise((resolve, reject) => {
    const worker = new Worker('stage-worker.js');
    worker.onmessage = (event) => {
      if (event.data.progress) {
        if (onProgress) onProgress(event.data);
        return;
      }
      worker.terminate();
      if (event.data.ok) resolve(event.data);
      else reject(new Error(event.data.message));
    };
    worker.onerror = (event) => {
      worker.terminate();
      reject(new Error(event.message || 'the worker failed to start'));
    };
    worker.postMessage({ name, size, piece, reportEvery: onProgress ? 256 * MIB : 0 });
  });
}

const WRITE_METHODS = [
  { id: 'writable-4MiB', run: (handle) => writeThroughWritable(handle, METHOD_SIZE, 4 * MIB, false) },
  { id: 'writable-16MiB', run: (handle) => writeThroughWritable(handle, METHOD_SIZE, 16 * MIB, false) },
  { id: 'writable-size-first-4MiB', run: (handle) => writeThroughWritable(handle, METHOD_SIZE, 4 * MIB, true) },
  { id: 'worker-sync-handle-4MiB', run: (_handle, name) => writeInWorker(name, METHOD_SIZE, 4 * MIB) },
];

action('stageCompare', 'stageStatus', async () => {
  if (!features.opfs) {
    status('stageStatus', '這個瀏覽器沒有內部儲存空間的 API');
    return;
  }
  const directory = await navigator.storage.getDirectory();
  const first = await storageNow();
  log(`e.method start size=${METHOD_SIZE} usage=${mib(first.usage)} quota=${mib(first.quota)}`);
  for (const [index, method] of WRITE_METHODS.entries()) {
    const name = `l0-method-${index}.bin`;
    status('stageStatus', `寫入方式 ${index + 1} / ${WRITE_METHODS.length}:${method.id}`);
    await directory.removeEntry(name).catch(() => undefined);
    const before = await storageNow();
    const started = performance.now();
    let outcome;
    try {
      const handle = await directory.getFileHandle(name, { create: true });
      await method.run(handle, name);
      const size = (await handle.getFile()).size;
      outcome = `sizeOk=${size === METHOD_SIZE}`;
    } catch (error) {
      outcome = `ERROR ${describeError(error)}`;
    }
    const ms = performance.now() - started;
    const after = await storageNow();
    await directory.removeEntry(name).catch(() => undefined);
    const removed = await storageNow();
    log(
      `e.method name=${method.id} ${outcome} time=${seconds(ms)} before=${mib(before.usage)} after=${mib(after.usage)} ` +
        `added=${mib(after.usage - before.usage)} afterRemove=${mib(removed.usage)} quota=${mib(removed.quota)}`,
    );
  }
  // The reported figure may lag: read it once more a little later
  await new Promise((resolve) => setTimeout(resolve, 5000));
  const last = await storageNow();
  log(`e.method end usage=${mib(last.usage)} quota=${mib(last.quota)}`);
  status('stageStatus', `寫入方式比較完成;瀏覽器回報這個網站已用 ${mib(last.usage)}`);
});

// ───────────────────────── g. Piece-by-piece writes to a local folder ─────────────────────────

async function writeTest(directory, where) {
  const size = Number($('writeSize').value);
  const name = `l0-write-${size}.bin`;
  log(`g.start where=${where} size=${size} piece=${mib(PIECE)}${heap()}`);
  const handle = await directory.getFileHandle(name, { create: true });
  const writable = await handle.createWritable();
  const started = performance.now();
  let writeMs = 0;
  let nextLog = 256 * MIB;
  try {
    for (let position = 0; position < size; ) {
      const end = Math.min(size, position + PIECE);
      const bytes = gen.range(position, end);
      const before = performance.now();
      await writable.write(bytes);
      writeMs += performance.now() - before;
      position = end;
      status('writeStatus', `寫入 ${mib(position)} / ${mib(size)}`);
      if (position >= nextLog) {
        nextLog += 256 * MIB;
        log(`g.progress at=${mib(position)} elapsed=${seconds(performance.now() - started)} write=${seconds(writeMs)}${heap()}`);
      }
    }
  } catch (error) {
    await writable.abort().catch(() => undefined);
    await directory.removeEntry(name).catch(() => undefined);
    throw error;
  }
  const beforeClose = performance.now();
  await writable.close();
  const closeMs = performance.now() - beforeClose;
  const file = await handle.getFile();
  log(`g.written size=${file.size} sizeOk=${file.size === size} write=${seconds(writeMs)} (${rate(size, writeMs)}) close=${seconds(closeMs)} wall=${seconds(performance.now() - started)}${heap()}`);

  const read = await hashFile(file, PIECE, 'g.readback', 'writeStatus');
  const expected = await expectedHash(size, 'writeStatus');
  const same = read.hex === expected;
  log(`g.verify ${same ? 'SAME' : 'DIFFERENT'} expected=${expected}`);
  await directory.removeEntry(name);
  log('g.removed the test file');
  status('writeStatus', `${where}:寫入 ${mib(size)} ${seconds(writeMs)}(${rate(size, writeMs)}),關檔 ${seconds(closeMs)},內容${same ? '正確' : '不正確'};測試檔已刪除`);
}

action('writeFolder', 'writeStatus', async () => {
  if (!features.directoryPicker) {
    status('writeStatus', '這個瀏覽器不能選資料夾(需要電腦的 Chrome 或 Edge)');
    return;
  }
  const directory = await self.showDirectoryPicker({ mode: 'readwrite' });
  await writeTest(directory, 'folder');
});

action('writeOpfs', 'writeStatus', async () => {
  if (!features.opfs) {
    status('writeStatus', '這個瀏覽器沒有內部儲存空間的 API');
    return;
  }
  const estimate = await navigator.storage.estimate();
  log(`g.opfs quota=${mib(estimate.quota ?? 0)} usage=${mib(estimate.usage ?? 0)}`);
  await writeTest(await navigator.storage.getDirectory(), 'opfs');
});

// ───────────────────────── Copy the log ─────────────────────────

$('copyLog').addEventListener('click', async () => {
  const text = [...previousLines, ...lines].join('\n');
  try {
    await navigator.clipboard.writeText(text);
    $('copyLog').textContent = '已複製';
  } catch {
    // No clipboard permission: select the log so it can be copied by hand
    const range = document.createRange();
    range.selectNodeContents($('log'));
    const selection = getSelection();
    selection.removeAllRanges();
    selection.addRange(range);
    $('copyLog').textContent = '已選取,請手動複製';
  }
  setTimeout(() => {
    $('copyLog').textContent = '複製測試紀錄';
  }, 2000);
});

$('clearLog').addEventListener('click', () => {
  lines.length = 0;
  previousLines.length = 0;
  $('log').textContent = '';
  saveLog();
});
