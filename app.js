// ───────────────────────── Hash worker ─────────────────────────

let worker = null;
let nextJob = 1;
const jobs = new Map();

function hashWorker() {
  if (worker !== null) return worker;
  worker = new Worker('hash-worker.js');
  worker.onmessage = (event) => {
    const job = jobs.get(event.data.id);
    if (!job) return;
    if (event.data.type === 'progress') job.onProgress(event.data);
    else {
      jobs.delete(event.data.id);
      if (event.data.type === 'done') job.resolve(event.data);
      else job.reject(new Error(event.data.message));
    }
  };
  worker.onerror = (event) => {
    for (const job of jobs.values()) job.reject(new Error(`worker error: ${event.message}`));
    jobs.clear();
    worker = null;
  };
  return worker;
}

function runInWorker(message, onProgress) {
  return new Promise((resolve, reject) => {
    const id = nextJob++;
    jobs.set(id, { resolve, reject, onProgress: onProgress ?? (() => undefined) });
    hashWorker().postMessage({ id, ...message });
  });
}

/** SHA-256 of the first `size` generated bytes, computed once per size */
const expectedHashes = new Map();
async function expectedHash(size, statusId) {
  const known = expectedHashes.get(size);
  if (known !== undefined) return known;
  const result = await runInWorker({ cmd: 'gen', size, piece: PIECE }, (p) => status(statusId, `算對照用的雜湊 ${mib(p.done)} / ${mib(p.total)}`));
  expectedHashes.set(size, result.hex);
  return result.hex;
}

// ───────────────────────── c. Chunked SHA-256 ─────────────────────────

async function nativeHex(bytes) {
  return sha.toHex(new Uint8Array(await crypto.subtle.digest('SHA-256', bytes)));
}

action('hashCheck', 'hashStatus', async () => {
  const lengths = [0, 1, 55, 56, 57, 63, 64, 65, 119, 120, 128, 1000, 65535, 65536, 65537, MIB + 3];
  let passed = 0;
  let total = 0;
  for (const length of lengths) {
    const data = new Uint8Array(length);
    // getRandomValues takes at most 65536 bytes per call
    for (let offset = 0; offset < length; offset += 65536) crypto.getRandomValues(data.subarray(offset, Math.min(length, offset + 65536)));
    const expected = await nativeHex(data);
    for (let round = 0; round < 4; round++) {
      const hasher = sha.create();
      for (let position = 0; position < length; ) {
        const take = round === 0 ? length : 1 + Math.floor(Math.random() * Math.min(length - position, 300));
        hasher.update(data.subarray(position, position + take));
        position += take;
      }
      total++;
      if (sha.toHex(hasher.digest()) === expected) passed++;
      else log(`c.check MISMATCH length=${length} round=${round}`);
    }
  }
  log(`c.check: ${passed}/${total} match WebCrypto`);
  status('hashStatus', `正確性:${passed}/${total}`);
});

action('hashWorker', 'hashStatus', async () => {
  const size = Number($('hashSize').value);
  const started = performance.now();
  const result = await runInWorker({ cmd: 'gen', size, piece: PIECE }, (p) => status('hashStatus', `Worker:${mib(p.done)} / ${mib(p.total)},雜湊 ${rate(p.done, p.hashMs)}`));
  expectedHashes.set(size, result.hex);
  const wall = performance.now() - started;
  log(`c.worker size=${mib(size)} hash=${seconds(result.hashMs)} (${rate(size, result.hashMs)}) generate=${seconds(result.readMs)} wall=${seconds(wall)} sha256=${result.hex}${heap()}`);
  status('hashStatus', `Worker:${mib(size)} 雜湊 ${seconds(result.hashMs)}(${rate(size, result.hashMs)})`);
});

action('hashMain', 'hashStatus', async () => {
  const size = Math.min(Number($('hashSize').value), 1024 * MIB);
  const hasher = sha.create();
  let hashMs = 0;
  let longest = 0;
  for (let position = 0; position < size; position += PIECE) {
    const bytes = gen.range(position, Math.min(size, position + PIECE));
    const started = performance.now();
    hasher.update(bytes);
    const took = performance.now() - started;
    hashMs += took;
    longest = Math.max(longest, took);
    status('hashStatus', `主執行緒:${mib(position)} / ${mib(size)}`);
    // Let the page repaint between pieces
    await new Promise((resolve) => setTimeout(resolve));
  }
  const hex = sha.toHex(hasher.digest());
  const known = expectedHashes.get(size);
  log(`c.main size=${mib(size)} hash=${seconds(hashMs)} (${rate(size, hashMs)}) longestPiece=${longest.toFixed(0)}ms sha256=${hex}${known ? ` sameAsWorker=${known === hex}` : ''}${heap()}`);
  status('hashStatus', `主執行緒:${mib(size)} 雜湊 ${seconds(hashMs)}(${rate(size, hashMs)}),每 4 MiB 最久卡 ${longest.toFixed(0)} ms`);
});

action('hashNative', 'hashStatus', async () => {
  const size = 64 * MIB;
  const bytes = gen.range(0, size);
  let started = performance.now();
  const native = await nativeHex(bytes);
  const nativeMs = performance.now() - started;
  const hasher = sha.create();
  started = performance.now();
  hasher.update(bytes);
  const mine = sha.toHex(hasher.digest());
  const mineMs = performance.now() - started;
  log(`c.native size=${mib(size)} webcrypto=${seconds(nativeMs)} (${rate(size, nativeMs)}) plainJs=${seconds(mineMs)} (${rate(size, mineMs)}) match=${native === mine}`);
  status('hashStatus', `WebCrypto ${rate(size, nativeMs)};純 JavaScript ${rate(size, mineMs)};結果${native === mine ? '相同' : '不同'}`);
});

// ───────────────────────── f. Pick a large file, read it in slices ─────────────────────────

/** Hashes a File in the worker, logging every 256 MiB; resolves to the worker's result */
async function hashFile(file, piece, tag, statusId) {
  const started = performance.now();
  let nextLog = 256 * MIB;
  let last = { at: started, done: 0 };
  const result = await runInWorker({ cmd: 'file', file, piece }, (p) => {
    status(statusId, `${mib(p.done)} / ${mib(p.total)}(${((p.done / p.total) * 100).toFixed(0)}%)`);
    if (p.done >= nextLog) {
      nextLog += 256 * MIB;
      const now = performance.now();
      log(`${tag} at=${mib(p.done)} elapsed=${seconds(now - started)} last256=${rate(p.done - last.done, now - last.at)} read=${seconds(p.readMs)} hash=${seconds(p.hashMs)}${heap()}`);
      last = { at: now, done: p.done };
    }
  });
  const wall = performance.now() - started;
  log(`${tag} done size=${file.size} wall=${seconds(wall)} (${rate(file.size, wall)}) read=${seconds(result.readMs)} hash=${seconds(result.hashMs)} sha256=${result.hex}${heap()}`);
  return { ...result, wall };
}

let pickedAt = 0;
$('filePick').addEventListener('click', () => {
  pickedAt = performance.now();
});
$('filePick').addEventListener('change', () => {
  const file = $('filePick').files[0];
  $('fileStart').disabled = !file;
  if (!file) return;
  // The name is left out of the log on purpose
  log(`f.picked size=${file.size} (${mib(file.size)}) type=${file.type || '(none)'} sincePickerOpened=${seconds(performance.now() - pickedAt)}`);
  status('fileStatus', `已選:${mib(file.size)},${file.type || '未知類型'}`);
});

action('fileStart', 'fileStatus', async () => {
  const file = $('filePick').files[0];
  if (!file) return;
  const piece = Number($('filePiece').value);
  log(`f.start size=${file.size} piece=${mib(piece)}`);
  const result = await hashFile(file, piece, 'f', 'fileStatus');
  let verdict = '';
  // A file of exactly a download size is taken as a download of experiment e: compare it with the generated content
  const sizes = Array.from($('dlSize').options, (option) => Number(option.value));
  if (sizes.includes(file.size)) {
    const expected = await expectedHash(file.size, 'fileStatus');
    const same = expected === result.hex;
    log(`f.compare-with-generated size=${file.size} ${same ? 'SAME' : 'DIFFERENT'} expected=${expected}`);
    verdict = same ? ';和實驗 e 產生的內容一致' : ';和實驗 e 產生的內容不一致';
  }
  status('fileStatus', `完成:${mib(file.size)},${seconds(result.wall)}(${rate(file.size, result.wall)})${verdict}`);
});

// ───────────────────────── e. Streamed download through the Service Worker ─────────────────────────

function newToken() {
  return Array.from(crypto.getRandomValues(new Uint8Array(8)), (byte) => byte.toString(16).padStart(2, '0')).join('');
}

function refreshDownloadLink() {
  $('dlLink').href = `dl/${newToken()}?size=${$('dlSize').value}&mode=${$('dlMode').value}`;
}

const downloads = new Map();
let piecesServed = 0;

function onWorkerMessage(event) {
  const data = event.data;
  if (!data) return;
  if (data.type === 'need') {
    // The Service Worker asks for one piece of the content (mode=page)
    const bytes = gen.range(data.start, data.end);
    piecesServed++;
    event.ports[0].postMessage({ bytes: bytes.buffer }, [bytes.buffer]);
    return;
  }
  if (data.type !== 'dl') return;
  const seen = downloads.get(data.token) ?? { nextLog: 256 * MIB };
  downloads.set(data.token, seen);
  const where = `${mib(data.position)} / ${mib(data.size)}`;
  if (data.state === 'start') {
    log(`e.start token=${data.token} mode=${data.mode} size=${data.size} hasClientId=${data.clientId !== ''} hasResultingClientId=${data.resultingClientId !== ''}`);
    status('dlStatus', `開始:${mib(data.size)}`);
  } else if (data.state === 'progress') {
    status('dlStatus', `瀏覽器已讀取 ${where},${rate(data.position, data.elapsedMs)}`);
    if (data.position >= seen.nextLog) {
      seen.nextLog += 256 * MIB;
      log(`e.progress token=${data.token} pulled=${where} elapsed=${seconds(data.elapsedMs)} (${rate(data.position, data.elapsedMs)})${heap()}`);
    }
  } else {
    log(`e.${data.state} token=${data.token} pulled=${where} elapsed=${seconds(data.elapsedMs)}${data.message ? ` message=${data.message}` : ''} piecesServedByPage=${piecesServed}${heap()}`);
    const words = { done: '瀏覽器讀完了', cancel: '被取消', error: '發生錯誤' };
    status('dlStatus', `${words[data.state] ?? data.state}:${where},${seconds(data.elapsedMs)}`);
  }
}

async function setUpServiceWorker() {
  if (!features.serviceWorker) {
    status('dlStatus', '這個瀏覽器沒有 Service Worker');
    return;
  }
  navigator.serviceWorker.onmessage = onWorkerMessage;
  try {
    await navigator.serviceWorker.register('sw.js');
    await navigator.serviceWorker.ready;
    if (!navigator.serviceWorker.controller) {
      await new Promise((resolve) => {
        navigator.serviceWorker.addEventListener('controllerchange', resolve, { once: true });
        setTimeout(resolve, 3000);
      });
    }
    const controlled = !!navigator.serviceWorker.controller;
    log(`e.serviceWorker controlled=${controlled}`);
    status('dlStatus', controlled ? 'Service Worker 已接管' : 'Service Worker 尚未接管,請重新整理一次');
  } catch (error) {
    log(`e.serviceWorker ERROR ${describeError(error)}`);
    status('dlStatus', `Service Worker 註冊失敗:${describeError(error)}`);
  }
}

$('dlSize').addEventListener('change', refreshDownloadLink);
$('dlMode').addEventListener('change', refreshDownloadLink);
$('dlLink').addEventListener('click', () => {
  log(`e.click size=${$('dlSize').value} mode=${$('dlMode').value} visibility=${document.visibilityState}`);
  // A fresh token for the next download, once this navigation has started
  setTimeout(refreshDownloadLink, 1000);
});
document.addEventListener('visibilitychange', () => log(`page visibility=${document.visibilityState}`));
refreshDownloadLink();
setUpServiceWorker();

// ───────────────────────── g. Piece-by-piece writes to a local folder ─────────────────────────

async function writeTest(directory, where) {
  const size = Number($('writeSize').value);
  const name = `l0-write-${size}.bin`;
  log(`g.start where=${where} size=${size} piece=${mib(PIECE)}${heap()}`);
  const handle = await directory.getFileHandle(name, { create: true });
  const writable = await handle.createWritable();
  const started = performance.now();
  let writeMs = 0;
  let nextLog = 256 * MIB;
  try {
    for (let position = 0; position < size; ) {
      const end = Math.min(size, position + PIECE);
      const bytes = gen.range(position, end);
      const before = performance.now();
      await writable.write(bytes);
      writeMs += performance.now() - before;
      position = end;
      status('writeStatus', `寫入 ${mib(position)} / ${mib(size)}`);
      if (position >= nextLog) {
        nextLog += 256 * MIB;
        log(`g.progress at=${mib(position)} elapsed=${seconds(performance.now() - started)} write=${seconds(writeMs)}${heap()}`);
      }
    }
  } catch (error) {
    await writable.abort().catch(() => undefined);
    await directory.removeEntry(name).catch(() => undefined);
    throw error;
  }
  const beforeClose = performance.now();
  await writable.close();
  const closeMs = performance.now() - beforeClose;
  const file = await handle.getFile();
  log(`g.written size=${file.size} sizeOk=${file.size === size} write=${seconds(writeMs)} (${rate(size, writeMs)}) close=${seconds(closeMs)} wall=${seconds(performance.now() - started)}${heap()}`);

  const read = await hashFile(file, PIECE, 'g.readback', 'writeStatus');
  const expected = await expectedHash(size, 'writeStatus');
  const same = read.hex === expected;
  log(`g.verify ${same ? 'SAME' : 'DIFFERENT'} expected=${expected}`);
  await directory.removeEntry(name);
  log('g.removed the test file');
  status('writeStatus', `${where}:寫入 ${mib(size)} ${seconds(writeMs)}(${rate(size, writeMs)}),關檔 ${seconds(closeMs)},內容${same ? '正確' : '不正確'};測試檔已刪除`);
}

action('writeFolder', 'writeStatus', async () => {
  if (!features.directoryPicker) {
    status('writeStatus', '這個瀏覽器不能選資料夾(需要電腦的 Chrome 或 Edge)');
    return;
  }
  const directory = await self.showDirectoryPicker({ mode: 'readwrite' });
  await writeTest(directory, 'folder');
});

action('writeOpfs', 'writeStatus', async () => {
  if (!features.opfs) {
    status('writeStatus', '這個瀏覽器沒有內部儲存空間的 API');
    return;
  }
  const estimate = await navigator.storage.estimate();
  log(`g.opfs quota=${mib(estimate.quota ?? 0)} usage=${mib(estimate.usage ?? 0)}`);
  await writeTest(await navigator.storage.getDirectory(), 'opfs');
});

// ───────────────────────── Copy the log ─────────────────────────

$('copyLog').addEventListener('click', async () => {
  const text = lines.join('\n');
  try {
    await navigator.clipboard.writeText(text);
    $('copyLog').textContent = '已複製';
  } catch {
    // No clipboard permission: select the log so it can be copied by hand
    const range = document.createRange();
    range.selectNodeContents($('log'));
    const selection = getSelection();
    selection.removeAllRanges();
    selection.addRange(range);
    $('copyLog').textContent = '已選取,請手動複製';
  }
  setTimeout(() => {
    $('copyLog').textContent = '複製測試紀錄';
  }, 2000);
});

$('clearLog').addEventListener('click', () => {
  lines.length = 0;
  $('log').textContent = '';
});
